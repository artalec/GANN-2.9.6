import Foundation

/// Откладывает сброс состояния перетаскивания и позволяет его отменить.
///
/// Зачем: кнопка мыши отпускается раньше, чем система вызывает `performDrop`.
/// Если сбросить список перетаскиваемых элементов сразу при отпускании, бросок увидит
/// пустое состояние и ничего не перенесёт. Сброс откладывается на короткое время;
/// новое перетаскивание или явное завершение отменяют ещё не выполненный сброс,
/// поэтому старый сброс не может затереть следующее перетаскивание.
///
/// Использовать только на главном потоке.
final class DragEndGate {

    private var token = 0

    /// Запланировать действие через `delay` секунд. Предыдущее запланированное действие отменяется.
    func scheduleEnd(after delay: TimeInterval, _ action: @escaping () -> Void) {
        token += 1
        let mine = token
        DispatchQueue.main.asyncAfter(deadline: .now() + delay) { [weak self] in
            guard let self, self.token == mine else { return }
            action()
        }
    }

    /// Отменить запланированное действие.
    func cancel() {
        token += 1
    }
}
